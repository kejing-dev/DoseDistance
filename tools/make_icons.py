# 3D icon layers + 512 export (PIL)
try:
    from PIL import Image, ImageDraw
except ImportError:
    print("drawables written; PIL missing, no PNG layers")
    sys.exit(0)

S = 1024
K = S / 108.0
YELLOW = (242, 194, 48, 255)
INK = (27, 27, 27, 255)


def tile():
    im = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    ImageDraw.Draw(im).rounded_rectangle((40, 40, S - 40, S - 40), radius=220, fill=YELLOW)
    return im


def glyph(bg=None):
    im = Image.new("RGBA", (S, S), bg or (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    cx, cy = CX * K, CY * K
    for k in range(3):
        start = 60 + 120 * k
        pts = []
        for i in range(31):
            a = math.radians(start + 60 * i / 30)
            pts.append((cx + R_BLADE * K * math.cos(a), cy + R_BLADE * K * math.sin(a)))
        for i in range(31):
            a = math.radians(start + 60 - 60 * i / 30)
            pts.append((cx + R_IN * K * math.cos(a), cy + R_IN * K * math.sin(a)))
        d.polygon(pts, fill=INK)
    d.ellipse((cx - R_DOT * K, cy - R_DOT * K, cx + R_DOT * K, cy + R_DOT * K), fill=INK)
    for r, w in ARCS:
        rr = r * K
        lw = max(2, int(w * K))
        # PIL draws the width inwards from the box: grow the box by half a line so the line is centred on r
        ro = rr + lw / 2
        d.arc((cx - ro, cy - ro, cx + ro, cy + ro), 30, 150, fill=INK, width=lw)
        # round caps
        for a in (30, 150):
            px = cx + rr * math.cos(math.radians(a))
            py = cy + rr * math.sin(math.radians(a))
            h = lw / 2
            d.ellipse((px - h, py - h, px + h, py + h), fill=INK)
    return im


def alpha_white(im):
    w = Image.new("RGBA", im.size, (255, 255, 255, 0))
    w.putalpha(im.split()[3])
    return w


l0, l1 = tile(), glyph()
l0.save(os.path.join(DRAW, "icon_3d_layer_0.png"))
l1.save(os.path.join(DRAW, "icon_3d_layer_1.png"))
alpha_white(l0).save(os.path.join(DRAW, "icon_3d_sdf_0.png"))
alpha_white(l1).save(os.path.join(DRAW, "icon_3d_sdf_1.png"))
if len(sys.argv) > 1:
    full = Image.new("RGBA", (S, S), YELLOW)
    Image.alpha_composite(full, l1).resize((512, 512), Image.LANCZOS).save(sys.argv[1])
