# launcher foreground: 108 x 108 viewport, content inside the 66 dp safe zone (design appIcon.glyph)
CX, CY = 54.0, 45.0
R_BLADE, R_IN, R_DOT = 17.0, 5.1, 3.4
ARCS = [(24.0, 3.4), (29.5, 2.5), (35.0, 1.6)]  # 1 / 2 / 3 m rings: the farther, the thinner
paths = [f'    <path android:fillColor="#FF1B1B1B" android:pathData="{trefoil_path(CX, CY, R_BLADE, R_IN)}" />',
         f'    <path android:fillColor="#FF1B1B1B" android:pathData="{circle(CX, CY, R_DOT)}Z" />']
for r, w in ARCS:
    paths.append(f'    <path android:strokeColor="#FF1B1B1B" android:strokeWidth="{w}" android:strokeLineCap="round" android:pathData="{arc(CX, CY, r)}" />')
