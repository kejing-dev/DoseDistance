TAIL = "</vector>\n"


def stroke(d, w=2):
    return f'    <path android:pathData="{d}" android:strokeColor="#FFFFFFFF" android:strokeWidth="{w}" android:strokeLineCap="round" android:strokeLineJoin="round" />\n'


def fill(d):
    return f'    <path android:pathData="{d}" android:fillColor="#FFFFFFFF" />\n'


def dot(cx, cy, r):
    return fill(f"M{cx - r},{cy}a{r},{r} 0 1 0 {2 * r},0a{r},{r} 0 1 0 {-2 * r},0Z")


def circle(cx, cy, r):
    return f"M{cx - r},{cy}a{r},{r} 0 1 0 {2 * r},0a{r},{r} 0 1 0 {-2 * r},0"


def trefoil_path(cx, cy, R, r_in, fmt="{:.2f}"):
    """Three 60-degree blades between radii r_in and R, one pointing down (y grows downwards)."""
    f = lambda v: fmt.format(v)
    out = []
    for k in range(3):
        a0 = math.radians(60 + 120 * k)
        a1 = math.radians(120 + 120 * k)
        p = lambda r, a: (cx + r * math.cos(a), cy + r * math.sin(a))
        x0, y0 = p(R, a0)
        x1, y1 = p(R, a1)
        x2, y2 = p(r_in, a1)
        x3, y3 = p(r_in, a0)
        out.append(f"M{f(x0)},{f(y0)}A{f(R)},{f(R)} 0 0 1 {f(x1)},{f(y1)}L{f(x2)},{f(y2)}A{f(r_in)},{f(r_in)} 0 0 0 {f(x3)},{f(y3)}Z")
    return "".join(out)


def arc(cx, cy, r, a_from=30, a_to=150):
    """An arc below the centre, from a_from to a_to degrees (clockwise, y down)."""
    x0 = cx + r * math.cos(math.radians(a_from))
    y0 = cy + r * math.sin(math.radians(a_from))
    x1 = cx + r * math.cos(math.radians(a_to))
    y1 = cy + r * math.sin(math.radians(a_to))
    return f"M{x0:.2f},{y0:.2f}A{r},{r} 0 0 1 {x1:.2f},{y1:.2f}"


